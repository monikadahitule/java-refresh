package org.example;

public class EvenOdd {
    public static void main(String[] args){
        //printing a number is even or odd.
        int number = 0; //4,-3,5,0
        if(number % 2 == 0){
            System.out.println(number +" is even");
        } else{
            System.out.println(number + " is odd");
        }
    }
}
