package org.example;

public class Calculator {
        public void add(int a, int b){
            System.out.println("Inside add(int,int) "+ (a + b));
        }

        public void add(double a, double b){
            System.out.println("Inside add(double,double) " + (a + b));

        }

        public void add(int a, int b ,int c){
            System.out.println("Inside add(int,int,int) " +  (a + b + c));

        }


}
